"""Stop 훅이 답변을 막을 때 함께 보여 줄 '한 답변에 필요한 표지 전체' 체크리스트(2026-10-16 탐, 마찰 백로그 탐-에이전트마찰 #1).
마야 10/15: 훅마다 한 가지 표지만 알려 줘서 같은 답변을 두세 번 고쳐 써야 했다. 막힐 때 전체 목록을 한 번에 보고 한 번에 고친다."""

CHECKLIST = """
[한 답변에 필요한 표지 전체: 해당하는 줄만 맞추면 한 번에 통과합니다]
- 앞으로 할 일을 약속했다 → 이번 턴에 실행을 걸고 [지금 돌고 있는 것: 무엇, 로그 위치] / 안 돌면 [실행 대기: 이유와 풀리는 시각·조건]
- [실행 대기] 조건이 시각이 아니라 사건(회신·병합·클릭 등)이다 → 감시를 걸고 [감시 중: 스크립트 이름, 로그 위치] / 사람 결정만 기다리면 [실행 대기] 대신 '정하실 것'에 쓴다
- 사장님께 할 일을 부탁한다 → 같은 턴에 기록 검색(recall.py 또는 ledger_lint.py --find) + [사람 개입 필요: 사유]
- '막혔다'고 쓴다 → 같은 턴에 프로세스표·절차 기록 열람 + [해결 경로: 패스|MCP|신규 서비스|우회|개선 과제]
- 근거 없는 일반화가 있다 → 그 문장 끝에 [추정]
- 끝에 '정하실 것'(없으면 '없음')"""


def with_checklist(msg: str) -> str:
    return msg.rstrip() + "\n" + CHECKLIST.strip("\n")
